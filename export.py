"""Export the MeDRA evaluation traces and annotation files for the labelling page.

    C:/Users/joeba/medra/.venv/Scripts/python export.py --medra C:/Users/joeba/medra

Writes data.js: for each annotation file in eval/annotations, the trace text,
the sentence spans from MeDRA's own splitter (so every slot on the page is a
position the checker accepts) and the file's tags, concepts and topics.

The annotation files are read as they are at --ref (default origin/main, i.e.
what is pushed), not from the working folder, so local edits that are not
pushed never end up on the page. Run `git fetch` in the medra repo first.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).parent


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--medra", type=Path, required=True, help="path to the medra repo")
    parser.add_argument("--ref", default="origin/main", help="git ref to read the annotation files from")
    args = parser.parse_args()
    sys.path.insert(0, str(args.medra.resolve()))
    from eval.annotations import annotation_files, parse  # noqa: E402
    from eval.common import mine  # noqa: E402

    def git(*cmd: str) -> str:
        return subprocess.run(["git", "-C", str(args.medra), *cmd], capture_output=True, text=True, check=True,
                              encoding="utf-8").stdout

    names = [n.split("/")[-1] for n in git("ls-tree", "--name-only", args.ref, "eval/annotations/").split()]
    tmp = Path(tempfile.mkdtemp())
    for name in names:
        if name.endswith(".md") and name != "GUIDE.md":
            (tmp / name).write_text(git("show", f"{args.ref}:eval/annotations/{name}"), encoding="utf-8", newline="\n")

    traces, files = {}, []
    for path in annotation_files(tmp):
        a = parse(path)
        m = mine(a.trace_id)
        if a.trace_id not in traces:
            traces[a.trace_id] = {"title": m.trace.title, "prompt": m.trace.prompt, "text": m.text,
                                  "spans": [list(s) for s in m.spans]}
        front = re.match(r"\A---\n(.*?)\n---\n", path.read_text(encoding="utf-8").replace("\r\n", "\n"), re.DOTALL)
        meta = yaml.safe_load(front.group(1)) or {}
        files.append({
            "file": path.name,
            "trace": a.trace_id,
            "annotator": a.annotator,
            "drafted_by": meta.get("drafted_by"),
            "scratch": path.name.count(".") == 2,
            "status": a.status,
            "tags": {str(s): t for s, t in zip(a.starts, a.types)},
            "concepts": a.concepts,
            "topics": a.topics,
        })
    out = HERE / "data.js"
    out.write_text("// Generated by export.py. Do not edit.\nexport const DATA = "
                   + json.dumps({"traces": traces, "files": files}, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"wrote {out}: {len(files)} files, {len(traces)} traces, annotations from {args.ref}")


if __name__ == "__main__":
    main()
